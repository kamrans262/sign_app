import 'package:flutter/foundation.dart';
import 'package:flutter/widgets.dart';

import 'app_language_controller.dart';

/// Explicitly translate UI copy, never user-entered content, IDs or API values.
/// Untranslated source labels keep their exact English text during migration.
class AppStrings {
  const AppStrings(this.locale);
  final Locale locale;

  static const LocalizationsDelegate<AppStrings> delegate = _AppStringsDelegate();

  static AppStrings of(BuildContext context) =>
      Localizations.of<AppStrings>(context, AppStrings) ??
      const AppStrings(Locale('en'));

  String tr(String english) =>
      _translations[locale.languageCode]?[english] ?? english;

  String tabLabel(String english) {
    final label = tr(english);
    return switch (locale.languageCode) {
      'fr' => 'Onglet $label',
      'de' => 'Tab $label',
      'it' => 'Scheda $label',
      _ => '$label tab',
    };
  }
}

class _AppStringsDelegate extends LocalizationsDelegate<AppStrings> {
  const _AppStringsDelegate();

  @override
  bool isSupported(Locale locale) =>
      AppLanguages.fromCode(locale.languageCode) != null;

  @override
  Future<AppStrings> load(Locale locale) =>
      SynchronousFuture(AppStrings(AppLanguages.resolve([locale])));

  @override
  bool shouldReload(_AppStringsDelegate old) => false;
}

